// Supply-chain relationships between public companies.
//
// There is no free feed for this: supplier lists are not a market-data field,
// they are assembled from annual reports, supplier disclosures, teardowns and
// company announcements. So this file is hand-curated and deliberately
// conservative - a link is only here when the relationship has been stated by
// one of the two companies or is unambiguous from public teardowns.
//
// It is a map of *who supplies whom*, not a statement about revenue share, and
// it goes stale: sole-source parts get second-sourced, contracts move between
// assemblers. Treat it as a research starting point rather than a filing.
//
// Curated 2026-07 to reach every S&P 500 constituent, then extended to the
// whole Russell 1000. The back half of either index is banks, insurers, REITs,
// utilities and software, whose inputs are services rather than parts - so the
// links there are the disclosed ones of that kind: the index a fund licenses,
// the tower a carrier leases, the contractor that builds the grid, the cloud a
// platform runs on. Sparser than a chip teardown, and honestly so.
//
// Below the large-cap line the evidence is often sector-level rather than
// contract-level: a regional bank's card network and credit bureau are known,
// which one of the three core processors it uses is not. Where that is the
// case the note says what is actually known and stops there, and the weight
// stays at 1. Nine companies have no link at all - holding companies whose
// only relationship is ownership, and a few whose counterparties are private -
// and they open onto a map that says so rather than onto an invented one.
//
// Edge notes carry the specific part or role so a claim can be checked rather
// than taken on trust.

// Two levels, on purpose.
//
// GROUPS carry the colour, and they describe *position in the chain* rather
// than stock-market sector. That is the axis that survives scale: once the
// map covers the whole S&P 500, "Foundry & Packaging" says nothing about a
// water utility or a REIT, whereas "who makes the inputs / who assembles /
// who sells it" reads the same in semiconductors, groceries and aerospace.
//
// There are seven because seven is what colour can hold in a node-link
// diagram: any two dots can end up touching, so *every* pair has to stay
// separable, not just the pairs a legend happens to list adjacently. Searching
// the colour space under that constraint tops out here - these seven clear
// both floors on the light and the dark panel (worst pair ΔE 15.7 normal, 8.4
// simulated for colour-vision deficiency), and an eighth drops the closest
// pair below what normal colour vision resolves.
//
// The company's real industry - 112 of them across the index - travels as
// *text*, on the node card and in the legend breakdown. Detail colour cannot
// carry is not thrown away, it just stops being a colour.
